/**
 * ดึงชื่อวันหยุดของวันที่ระบุ (YYYY-MM-DD) ถ้ามี
 */
export function getThaiHoliday(dateString) {
  if (!dateString) return null;

  // ตรวจสอบวันหยุดแปรผัน (ปี-เดือน-วัน)
  if (THAI_VARIABLE_HOLIDAYS[dateString]) {
    return THAI_VARIABLE_HOLIDAYS[dateString];
  }

  // ตรวจสอบวันหยุดประจำปี (เดือน-วัน)
  const parts = dateString.split("-");
  if (parts.length === 3) {
    const monthDay = `${parts[1]}-${parts[2]}`;
    if (THAI_FIXED_HOLIDAYS[monthDay]) {
      return THAI_FIXED_HOLIDAYS[monthDay];
    }
  }

  return null;
}

/**
 * ตรวจสอบว่าวันที่ดังกล่าวเป็นวันหยุดราชการหรือไม่
 */
export function isThaiHoliday(dateString) {
  return !!getThaiHoliday(dateString);
}
